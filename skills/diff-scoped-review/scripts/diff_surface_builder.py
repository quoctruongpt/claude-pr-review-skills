def is_generated(path: str, added_text: list[str]) -> tuple[bool, str]:
    """Return (generated, reason). Path rules first, then in-file markers."""
    base = path.rsplit("/", 1)[-1]
    # A migration is never "generated", even when a tool scaffolded it; only EF Core's designer/snapshot files are
    if re.search(r"(^|/)migrations?/", path, re.I) and not path.endswith((".Designer.cs", "ModelSnapshot.cs")):
        return False, ""
    if base in GENERATED_EXACT:
        return True, f"lock/vendored file ({base})"
    for suf in GENERATED_SUFFIX:
        if path.endswith(suf):
            return True, f"generated suffix ({suf})"
    probe = path if path.startswith("/") else "/" + path
    for part in GENERATED_DIR_PARTS:
        if part in probe:
            return True, f"generated directory ({part.strip('/')})"
    head = " ".join(added_text[:5]).lower()
    for marker in GENERATED_MARKERS:
        if marker in head:
            return True, f"generator marker in header ({marker})"
    return False, ""


def _blank(entry: dict[str, Any]) -> dict[str, Any]:
    return entry


def parse_diff(text: str) -> list[dict[str, Any]]:
    """Parse a unified diff (git or plain) into per-file surface records."""
    files: list[dict[str, Any]] = []
    cur: dict[str, Any] | None = None
    hunk_no = 0
    old_ln = new_ln = 0
    in_hunk = False

    def flush() -> None:
        nonlocal cur
        if cur is not None:
            files.append(cur)
            cur = None

    def new_file(path: str, old_path: str | None) -> dict[str, Any]:
        return {
            "path": path,
            "old_path": old_path,
            "change_kind": "modified",
            "added_lines": [],
            "removed_lines": [],
            "context_lines": [],
            "added_text": [],
            "removed_text": [],
            "hunks": [],
        }

    for raw in text.splitlines():
        m = DIFF_GIT_RE.match(raw)
        if m:
            flush()
            hunk_no = 0
            in_hunk = False
            cur = new_file(m.group("b"), m.group("a"))
            continue

        if cur is None:
            # Plain diff with no `diff --git` header: open a file on `--- `.
            if raw.startswith("--- "):
                cur = new_file("<unknown>", raw[4:].strip() or None)
                hunk_no = 0
                in_hunk = False
            else:
                continue

        if raw.startswith("new file mode"):
            cur["change_kind"] = "added"
            continue
        if raw.startswith("deleted file mode"):
            cur["change_kind"] = "deleted"
            continue
        if raw.startswith("rename from "):
            cur["change_kind"] = "renamed"
            cur["old_path"] = raw[len("rename from ") :].strip()
            continue
        if raw.startswith("rename to "):
            cur["change_kind"] = "renamed"
            cur["path"] = raw[len("rename to ") :].strip()
            continue
        if raw.startswith("Binary files") or raw.startswith("GIT binary patch"):
            cur["change_kind"] = "binary"
            in_hunk = False
            continue
        if raw.startswith("--- "):
            in_hunk = False
            val = raw[4:].strip()
            if val != "/dev/null":
                cur["old_path"] = val[2:] if val.startswith(("a/", "b/")) else val
            continue
        if raw.startswith("+++ "):
            in_hunk = False
            val = raw[4:].strip()
            if val != "/dev/null":
                p = val[2:] if val.startswith(("a/", "b/")) else val
                if cur["path"] == "<unknown>":
                    cur["path"] = p
            continue

        hm = HUNK_RE.match(raw)
        if hm:
            hunk_no += 1
            old_ln = int(hm.group("old_start"))
            new_ln = int(hm.group("new_start"))
            oc = int(hm.group("old_count") or 1)
            nc = int(hm.group("new_count") or 1)
            cur["hunks"].append(
                {
                    "id": f"H{hunk_no}",
                    "header": raw.split("@@")[1].strip() if "@@" in raw else raw,
                    "section": hm.group("ctx").strip(),
                    "old_start": old_ln,
                    "old_end": old_ln + max(oc - 1, 0),
                    "new_start": new_ln,
                    "new_end": new_ln + max(nc - 1, 0),
                    "added": 0,
                    "removed": 0,
                }
            )
            in_hunk = True
            continue

        if not in_hunk:
            continue
        if raw.startswith("\\"):  # \ No newline at end of file
            continue

        tag, body = (raw[:1], raw[1:]) if raw else (" ", "")
        if tag == "+":
            cur["added_lines"].append(new_ln)
            cur["added_text"].append(body)
            cur["hunks"][-1]["added"] += 1
            new_ln += 1
        elif tag == "-":
            cur["removed_lines"].append(old_ln)
            cur["removed_text"].append(body)
            cur["hunks"][-1]["removed"] += 1
            old_ln += 1
        elif tag == " ":
            cur["context_lines"].append(new_ln)
            old_ln += 1
            new_ln += 1
        else:
            in_hunk = False

    flush()
    return files


def finalize(files: list[dict[str, Any]], keep_text: bool) -> dict[str, Any]:
    out_files = []
    for f in files:
        added_t = f.pop("added_text")
        removed_t = f.pop("removed_text")
        gen, gen_reason = is_generated(f["path"], added_t)

        a_norm = sorted(s.strip() for s in added_t if s.strip())
        r_norm = sorted(s.strip() for s in removed_t if s.strip())
        ws_only = bool(added_t or removed_t) and a_norm == r_norm

        f["generated"] = gen
        f["generated_reason"] = gen_reason
        f["whitespace_or_move_only"] = ws_only
        f["added_count"] = len(f["added_lines"])
        f["removed_count"] = len(f["removed_lines"])
        if keep_text:
            f["added_text"] = added_t
            f["removed_text"] = removed_t
        out_files.append(f)

    totals = {
        "files": len(out_files),
        "added_lines": sum(f["added_count"] for f in out_files),
        "removed_lines": sum(f["removed_count"] for f in out_files),
        "hunks": sum(len(f["hunks"]) for f in out_files),
        "generated_files": sum(1 for f in out_files if f["generated"]),
        "binary_files": sum(1 for f in out_files if f["change_kind"] == "binary"),
    }
    reviewable = [f for f in out_files if not f["generated"] and f["change_kind"] != "binary"]
    totals["reviewable_files"] = len(reviewable)
    totals["reviewable_added_lines"] = sum(f["added_count"] for f in reviewable)
    return {"schema": "review_surface.v1", "files": out_files, "totals": totals}


