def read_input(args: argparse.Namespace) -> str:
    if args.sample:
        return SAMPLE_DIFF
    if args.git_range:
        cmd = ["git", "diff", "--no-color", "-M", args.git_range]
        try:
            res = subprocess.run(cmd, capture_output=True, text=True, check=False)
        except FileNotFoundError:
            sys.exit("git not found on PATH")
        if res.returncode != 0:
            sys.exit(f"git diff failed: {res.stderr.strip()}")
        return res.stdout
    if args.diff:
        with open(args.diff, encoding="utf-8", errors="replace") as fh:
            return fh.read()
    if sys.stdin.isatty():
        sys.exit("no diff given: pass --diff FILE, --git-range RANGE, --sample, or pipe a diff on stdin")
    return sys.stdin.read()


def render_text(surface: dict[str, Any]) -> str:
    t = surface["totals"]
    lines = [
        "REVIEW SURFACE",
        f"  files {t['files']}  (reviewable {t['reviewable_files']}, generated {t['generated_files']}, binary {t['binary_files']})",
        f"  lines +{t['added_lines']} -{t['removed_lines']}  across {t['hunks']} hunks",
        f"  reviewable added lines: {t['reviewable_added_lines']}",
        "",
    ]
    for f in surface["files"]:
        marks = []
        if f["generated"]:
            marks.append(f"GENERATED: {f['generated_reason']}")
        if f["whitespace_or_move_only"]:
            marks.append("WHITESPACE/MOVE-ONLY")
        if f["change_kind"] != "modified":
            marks.append(f["change_kind"].upper())
        suffix = f"  [{' | '.join(marks)}]" if marks else ""
        lines.append(f"{f['path']}  +{f['added_count']} -{f['removed_count']}{suffix}")
        if f["old_path"] and f["old_path"] != f["path"]:
            lines.append(f"    renamed from {f['old_path']}")
        for h in f["hunks"]:
            lines.append(
                f"    {h['id']}  new {h['new_start']}-{h['new_end']}  "
                f"old {h['old_start']}-{h['old_end']}  +{h['added']} -{h['removed']}"
                + (f"  // {h['section']}" if h["section"] else "")
            )
    if not surface["files"]:
        lines.append("(no files parsed — is the input a unified diff?)")
    return "\n".join(lines)


def main() -> int:
    p = argparse.ArgumentParser(
        description="Parse a unified diff into a review surface (the set of lines a diff-scoped review is allowed to block on).",
        epilog="Use three-dot ranges: `--git-range main...HEAD` diffs from the merge base. "
               "Two-dot (`main..HEAD`) also shows commits added to main since you branched, as removals.",
    )
    src = p.add_mutually_exclusive_group()
    src.add_argument("--diff", metavar="FILE", help="unified diff file (e.g. from `gh pr diff N > f.diff`)")
    src.add_argument("--git-range", metavar="RANGE", help="run `git diff -M RANGE` (use three dots: main...HEAD)")
    src.add_argument("--sample", action="store_true", help="run on a built-in sample diff")
    p.add_argument("--output", choices=["text", "json"], default="text", help="output format (default: text)")
    p.add_argument("--keep-text", action="store_true", help="include added/removed line text in JSON output")
    p.add_argument("--out", metavar="FILE", help="write output to FILE instead of stdout")
    args = p.parse_args()

    text = read_input(args)
    surface = finalize(parse_diff(text), args.keep_text)
    rendered = json.dumps(surface, indent=2) if args.output == "json" else render_text(surface)

    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(rendered + "\n")
        print(f"wrote {args.out}")
    else:
        print(rendered)
    return 0 if surface["files"] else 2


if __name__ == "__main__":
    sys.exit(main())
