#!/usr/bin/env python3
"""Parse a unified diff into a review surface.

The review surface is the ground truth for "what is actually in this PR":
which files changed, which line numbers were added (new side), which were
removed (old side), and which hunk each line belongs to. Every finding in a
diff-scoped review must anchor to something in here.

Stdlib only. No network, no LLM calls.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from typing import Any

HUNK_RE = re.compile(
    r"^@@ -(?P<old_start>\d+)(?:,(?P<old_count>\d+))? "
    r"\+(?P<new_start>\d+)(?:,(?P<new_count>\d+))? @@(?P<ctx>.*)$"
)
DIFF_GIT_RE = re.compile(r"^diff --git a/(?P<a>.*?) b/(?P<b>.*)$")

# Files whose diff lines are machine-written. Reviewing them line by line is
# wasted attention; what matters is "why did this change" at the file level.
